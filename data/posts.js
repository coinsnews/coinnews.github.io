// Utility Helper Functions for Blog Engine
window.CrypticBlogEngine = {
  getAllPosts() {
    return window.CRYPTIC_POSTS || [];
  },

  getPostBySlug(slug) {
    if (!slug) return null;
    const cleanSlug = slug.trim().toLowerCase();
    return window.CRYPTIC_POSTS.find(p => p.slug.toLowerCase() === cleanSlug || this.slugify(p.title) === cleanSlug);
  },

  getFeaturedPost() {
    const posts = this.getAllPosts();
    return posts.find(p => p.featured) || posts[0];
  },

  getRecentPosts(limit = 6) {
    const posts = this.getAllPosts();
    return posts.slice(0, limit);
  },

  slugify(text) {
    return text
      .toString()
      .toLowerCase()
      .trim()
      .replace(/[\s\W-]+/g, '-')
      .replace(/^-+|-+$/g, '');
  }
};
